"""Stage 5, step 3: do two independently trained SER models agree on our data?

audeering (wav2vec2-large-robust, primary; feeds Stages 2-3) vs odyssey (WavLM-large, Odyssey 2024 baseline). Both
were trained on MSP-Podcast, so agreement is not proof of validity, but disagreement is a warning: a flag that one
model fires and the other does not is describing the model, not the speaker.

Checks (unique recordings; rater correlations on train only, same bootstrap test as Stage 3):
  1. window level      Spearman raw and speaker-relative z, per attribute
  2. answer level      Spearman of answer means, raw and within-speaker (answer minus the speaker's mean),
                       ICC (speaker share) per model
  3. flags / classes   tension_rise (run >= rule min_run_s) and the composure extremes (within-speaker arousal, train
                       p15 / p85 cut): agreement and Cohen's kappa
  4. rater relation    do the key Stage 3 findings replicate with the second model?

Inputs   stage5_ser/tables/windows_audeering.csv (with z columns; extract_ser_descriptors.py), windows_odyssey.csv
         (raw; run_ser_windows.py --model odyssey), Stage 2 tables (via stage3_validate_recruitview.load_all)
Outputs  stage5_ser/model_agreement.md, stage5_ser/tables/segment_ser_odyssey.csv, tables/model_agreement.csv

Run:  python scripts/explainability/ser_model_agreement.py [--n-boot 500]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

sys.path.insert(0, str(Path(__file__).resolve().parent))
import paths as P  # noqa: E402
import extract_ser_descriptors as ES  # noqa: E402
import stage3_validate_recruitview as S3  # noqa: E402
import stage0_confound_audit as s0  # noqa: E402

ATTRS = ES.ATTRS
SHORT = s0.TARGET_SHORT
OUT = P.S5 / "model_agreement.md"


def kappa(a: np.ndarray, b: np.ndarray) -> float:
    a, b = np.asarray(a, bool), np.asarray(b, bool)
    po = (a == b).mean()
    pe = a.mean() * b.mean() + (1 - a.mean()) * (1 - b.mean())
    return float((po - pe) / (1 - pe)) if pe < 1 else np.nan


def within(df: pd.DataFrame, col: str) -> pd.Series:
    return df[col] - df.groupby("participant")[col].transform("mean")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--n-boot", type=int, default=500)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()

    seg = pd.read_csv(P.SEGMENTS, dtype={"id": str, "participant": str, "duplicate_of": str})
    keys = seg[["id", "participant", "duplicate_of"]].assign(group=lambda d: d["duplicate_of"].fillna(d["id"]))
    wa = pd.read_csv(P.s5_windows("audeering"), dtype={"id": str})
    wo = pd.read_csv(P.s5_windows("odyssey"), dtype={"id": str})
    wo = wo[[c for c in wo.columns if not c.endswith("_z")]]
    # same windows -> reuse audeering's window pitch (model-independent)
    wo = wo.merge(wa[["id", "t_start", "f0_z"]], on=["id", "t_start"], how="left").reset_index(drop=True)
    for a in ATTRS:
        wo[f"{a}_z"] = ES.speaker_z(wo, keys, a)
    rows = [{"id": cid, **ES.answer_measures(g)} for cid, g in wo.groupby("id")]
    ser_o = keys[["id"]].merge(pd.DataFrame(rows), on="id", how="left")
    ser_o.to_csv(P.S5_TABLES / "segment_ser_odyssey.csv", index=False)

    min_run = float(json.loads(P.PERCENTILE_TABLES.read_text())["flag_rules"]["tension_rise"]["min_run_s"])

    L, rec = [], []
    add = L.append
    add("# Stage 5: agreement between two pretrained SER models\n")
    add("Generated by `scripts/explainability/ser_model_agreement.py`. Primary: `audeering` "
        "(wav2vec2-large-robust-12-ft-emotion-msp-dim). Second: `odyssey` (3loi/SER-Odyssey-Baseline-WavLM-Multi-Attributes; "
        "architecture re-implemented in `ser_models.py`, only the safetensors weights loaded, no repository code run). "
        "Same 4-s / 2-s windows. Both models were trained on MSP-Podcast: agreement shows the measurement is not an "
        "artefact of one network, not that it is valid for interviews.\n")

    # 1. windows
    m = wa.merge(wo, on=["id", "t_start"], suffixes=("_a", "_o"))
    m = m[m["speech_frac_a"] >= ES.MIN_SPEECH_FRAC]
    add("## 1. Window level (speech windows)\n")
    add(f"{len(m):,} windows.\n")
    add("| Attribute | Spearman raw | Spearman speaker-relative z |")
    add("|---|---|---|")
    for a in ATTRS:
        r_raw = spearmanr(m[f"{a}_a"], m[f"{a}_o"])[0]
        ok = m[f"{a}_z_a"].notna() & m[f"{a}_z_o"].notna()
        r_z = spearmanr(m.loc[ok, f"{a}_z_a"], m.loc[ok, f"{a}_z_o"])[0]
        add(f"| {a} | {r_raw:.2f} | {r_z:.2f} |")
        rec += [{"level": "window", "measure": a, "kind": "raw", "value": r_raw},
                {"level": "window", "measure": a, "kind": "z", "value": r_z}]
    ar_do = spearmanr(m["arousal_o"], m["dominance_o"])[0]
    add(f"\nArousal-dominance inside the second model: {ar_do:.2f} (audeering: "
        f"{spearmanr(m['arousal_a'], m['dominance_a'])[0]:.2f}).\n")

    # 2. answers
    ser_a = pd.read_csv(P.S5_SEGMENTS, dtype={"id": str})
    u = seg[~seg["is_duplicate"]][["id", "participant", "split"]]
    ua = u.merge(ser_a, on="id").merge(ser_o, on="id", suffixes=("_a", "_o"))
    add("## 2. Answer level (unique recordings)\n")
    add("Within-speaker = answer value minus the same speaker's mean: what the composure class and flags use.\n")
    add("| Measure | Spearman raw | Spearman within-speaker | ICC audeering | ICC odyssey |")
    add("|---|---|---|---|---|")
    for a in ATTRS:
        c = f"ser_{a}_mean"
        ok = ua[f"{c}_a"].notna() & ua[f"{c}_o"].notna()
        d = ua[ok]
        r_raw = spearmanr(d[f"{c}_a"], d[f"{c}_o"])[0]
        r_w = spearmanr(within(d, f"{c}_a"), within(d, f"{c}_o"))[0]
        icc_a = ES.icc1(d.rename(columns={f"{c}_a": "v"}), "v")
        icc_o = ES.icc1(d.rename(columns={f"{c}_o": "v"}), "v")
        add(f"| `{c}` | {r_raw:.2f} | {r_w:.2f} | {icc_a:.2f} | {icc_o:.2f} |")
        rec += [{"level": "answer", "measure": c, "kind": "raw", "value": r_raw},
                {"level": "answer", "measure": c, "kind": "within", "value": r_w}]
    for c in ("ser_tension_run_s", "ser_dominance_drop_sd"):
        ok = ua[f"{c}_a"].notna() & ua[f"{c}_o"].notna()
        r = spearmanr(ua.loc[ok, f"{c}_a"], ua.loc[ok, f"{c}_o"])[0]
        add(f"| `{c}` | {r:.2f} | | | |")
        rec.append({"level": "answer", "measure": c, "kind": "raw", "value": r})

    # 3. flags / classes
    add("\n## 3. Flags and classes\n")
    ok = ua["ser_tension_run_s_a"].notna() & ua["ser_tension_run_s_o"].notna()
    fa, fo = ua.loc[ok, "ser_tension_run_s_a"] >= min_run, ua.loc[ok, "ser_tension_run_s_o"] >= min_run
    both = (fa & fo).sum()
    add(f"- `tension_rise` (run >= {min_run:g} s): audeering {fa.mean():.1%}, odyssey {fo.mean():.1%}; of audeering's "
        f"flags, {both / max(fa.sum(), 1):.0%} also fire with odyssey; kappa **{kappa(fa, fo):.2f}**.")
    rec.append({"level": "flag", "measure": "tension_rise", "kind": "kappa", "value": kappa(fa, fo)})
    rec.append({"level": "flag", "measure": "tension_rise", "kind": "share_confirmed", "value": both / max(fa.sum(), 1)})
    for model in ("a", "o"):
        ua[f"aw_{model}"] = within(ua, f"ser_arousal_mean_{model}")
    tr = ua[ua["split"] == "train"]
    for pole, q in (("more activated than usual", 0.85), ("calmer than usual", 0.15)):
        sel = {}
        for model in ("a", "o"):
            cut = tr[f"aw_{model}"].quantile(q)
            v = ua[f"aw_{model}"]
            sel[model] = (v >= cut) if q > 0.5 else (v <= cut)
        ok = ua["aw_a"].notna() & ua["aw_o"].notna()
        k = kappa(sel["a"][ok], sel["o"][ok])
        conf = (sel["a"] & sel["o"])[ok].sum() / max(sel["a"][ok].sum(), 1)
        opp = (sel["a"][ok] & ((ua["aw_o"][ok] <= tr["aw_o"].quantile(0.15)) if q > 0.5
                               else (ua["aw_o"][ok] >= tr["aw_o"].quantile(0.85)))).sum() / max(sel["a"][ok].sum(), 1)
        add(f"- Composure '{pole}' (approx.: within-speaker arousal beyond train p{int(q * 100)}): {conf:.0%} of audeering's "
            f"answers also selected by odyssey, {opp:.1%} put in the opposite class; kappa **{k:.2f}**.")
        rec.append({"level": "class", "measure": pole, "kind": "kappa", "value": k})
    add("")

    # 4. raters
    add("## 4. Do the rater findings replicate? (train, unique recordings)\n")
    df = S3.unique_recordings(S3.load_all())
    oc = {f"{c}_odyssey": c for c in ("ser_arousal_mean", "ser_dominance_mean", "ser_valence_mean",
                                      "ser_tension_run_s", "ser_dominance_drop_sd")}
    df = df.merge(ser_o.rename(columns={v: k for k, v in oc.items()})[["id", *oc]], on="id", how="left")
    train = df[df["split"] == "train"].reset_index(drop=True)
    pairs = [(v, k) for k, v in oc.items()]
    feats = [f for p in pairs for f in p]
    print(f"bootstrap ({args.n_boot}) on {len(train)} train recordings ...", flush=True)
    corr = s0.correlation_audit(train, feats, args.n_boot, args.seed)
    corr.to_csv(P.S5_TABLES / "model_agreement_rater_corr.csv", index=False)

    def cell(feat, target, measure):
        r = corr[(corr.feature == feat) & (corr.target == target) & (corr.measure == measure)].iloc[0]
        star = "*" if (r.ci_low > 0 or r.ci_high < 0) else ""
        return f"{r.rho:+.2f}{star}"
    add("Spearman with the rater scores; * = 95% bootstrap CI (participants resampled) excludes 0. `between` = "
        "speaker means; `within (partial)` = within participants, controlling duration and question type "
        "(the comparison the feedback makes).\n")
    add("| Measure | Model | " + " | ".join(f"between {SHORT[t]}" for t in s0.TARGETS) + " | "
        + " | ".join(f"within {SHORT[t]}" for t in s0.TARGETS) + " |")
    add("|---|---|" + "---|" * (2 * len(s0.TARGETS)))
    for a_col, o_col in pairs:
        for name, col in (("audeering", a_col), ("odyssey", o_col)):
            add(f"| `{a_col}` | {name} | " + " | ".join(cell(col, t, "between") for t in s0.TARGETS) + " | "
                + " | ".join(cell(col, t, "within_partial") for t in s0.TARGETS) + " |")
    add("")
    pd.DataFrame(rec).to_csv(P.S5_TABLES / "model_agreement.csv", index=False)
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
