def test_answers(reuse: bool = False) -> None:
    lv = pd.read_csv(P.ANSWER_LEVELS, dtype={"id": str, "duplicate_of": str, "participant": str})
    val = lv[(lv["dataset"] == "recruitview") & (lv["split"] == "val") & ~lv["is_duplicate"].astype(bool)]
    sample = val.sample(N_ANSWERS, random_state=0).set_index("id")
    paths = A.load_clips().set_index("id")["audio_path"]
    sett = pd.read_csv(P.PITCH_SETTINGS, dtype={"participant": str}).set_index("participant")
    if reuse:  # report only, from the saved runs
        run_a = pd.read_csv(P.S12_TABLES / "answers_run_a.csv", dtype={"id": str})
        run_b = pd.read_csv(P.S12_TABLES / "answers_run_b.csv", dtype={"id": str})
    else:
        answers = [AA.Answer(id=i, audio=AA.load_audio(paths[i]), speaker_key=i) for i in sample.index]
        AA.measure(answers)
        given = {i: AA.Speaker(float(sett.loc[r.participant, "pitch_floor_hz"]),
                               float(sett.loc[r.participant, "pitch_ceiling_hz"]),
                               float(sett.loc[r.participant, "reference_f0_hz"]), float(r.speaker_f0_hz),
                               source="dataset tables") for i, r in sample.iterrows()}
        _, run_a, _ = AA.describe(answers, "recorded_answer", given)
        _, run_b, _ = AA.describe(answers, "recorded_answer", None)
        report_gpu_peak()
        P.S12_TABLES.mkdir(parents=True, exist_ok=True)
        run_a.to_csv(P.S12_TABLES / "answers_run_a.csv", index=False)
        run_b.to_csv(P.S12_TABLES / "answers_run_b.csv", index=False)

    ref = sample.reindex(run_a["id"])
    comp_rows = []
    for c in COMPONENTS:
        x, y = run_a[c].to_numpy(float), ref[c].to_numpy(float)
        ok = np.isfinite(x) & np.isfinite(y)
        comp_rows.append({"measure": c, "n": int(ok.sum()), "spearman": spearmanr(x[ok], y[ok])[0],
                          "median_abs_diff": float(np.median(np.abs(x[ok] - y[ok]))),
                          "max_abs_diff": float(np.max(np.abs(x[ok] - y[ok]))), "both_missing": int((~np.isfinite(x) & ~np.isfinite(y)).sum())})
    comp = pd.DataFrame(comp_rows)
    rows = []
    for dim in AA.AUDIO_DIMENSIONS:
        t_idx = ref[f"{dim}_index"].to_numpy(float)
        for run, t in (("A", run_a), ("B", run_b)):
            d = np.abs(t[f"{dim}_index"].to_numpy(float) - t_idx)
            same = t[f"{dim}_level"].to_numpy() == ref[f"{dim}_level"].to_numpy()
            near = (np.abs(t_idx - 20) <= CUT_MARGIN) | (np.abs(t_idx - 80) <= CUT_MARGIN)
            rows.append({"dimension": dim, "run": run, "n": len(t), "median_abs_index_diff": float(np.nanmedian(d)),
                         "max_abs_index_diff": float(np.nanmax(d)), "share_within_2": float(np.mean(d <= INDEX_TOL)),
                         "levels_equal": int(same.sum()), "level_differs_away_from_cut": int((~same & ~near).sum()),
                         "level_differs_near_cut": int((~same & near).sum())})
    lvl = pd.DataFrame(rows)
    pd.concat([comp.assign(kind="component"), lvl.assign(kind="index")]).to_csv(P.S12_TABLES / "answers_compare.csv",
                                                                                index=False)
    a = lvl[lvl["run"] == "A"]
    c1 = bool((comp["spearman"] >= RHO_MIN).all())
    c2 = bool((a["share_within_2"] >= 0.9).all())
    c3 = bool((a["level_differs_away_from_cut"] == 0).all())
    verdict = "PASS" if c1 and c2 and c3 else "FAIL"
    text = (f"## Test 1: one answer reproduces its dataset row ({verdict})\n\n"
            f"{N_ANSWERS} RecruitView validation answers, `recorded_answer` setting, from the audio files alone.\n\n"
            f"### Components (run A, speaker context from the tables)\n\n{md(comp)}\n\n"
            f"### Indices and levels\n\n{md(lvl)}\n\n"
            f"Criteria: 1. every component Spearman >= {RHO_MIN}: **{c1}**. 2. indices within {INDEX_TOL:g} points for "
            f">= 90% (run A): **{c2}**. 3. no level difference away from a cut (run A): **{c3}**.\n\n"
            "Run B (each clip alone, no speaker context) is reported, not a pass condition.\n")
    write_section("1_answers", text)
    print(text)


