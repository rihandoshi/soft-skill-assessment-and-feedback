import numpy as np
import pandas as pd
from scipy.stats import spearmanr

sys.path.insert(0, str(Path(__file__).resolve().parent))
import paths as P  # noqa: E402
import analyze_answer as AA  # noqa: E402
import run_verbatim_asr as A  # noqa: E402
from run_ser_windows import cap_gpu_memory, report_gpu_peak  # noqa: E402

N_ANSWERS = 30
COMPONENTS = ["p_interjection", "p_repetition_block", "sf_p_disfluent", "long_mid_pause_rate_per_min", "activation",
              "pitch_std_st", "speech_span_s", "f0_median_hz"]
INDEX_TOL, CUT_MARGIN, RHO_MIN = 2.0, 2.0, 0.98
SEG_TOL_S = 3.0


def md(df: pd.DataFrame, index: bool = False) -> str:
    """Markdown table without the optional tabulate dependency."""
    d = df.reset_index() if index else df
    fmt = lambda v: "" if pd.isna(v) else (f"{v:.4g}" if isinstance(v, float) else str(v))  # noqa: E731
    lines = ["| " + " | ".join(map(str, d.columns)) + " |", "|" + "---|" * len(d.columns)]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in d.itertuples(index=False)]
    return "\n".join(lines)


def write_section(name: str, text: str) -> None:
    """report.md holds one section per test; re-running a test replaces its section only."""
    P.S12.mkdir(parents=True, exist_ok=True)
    old = P.S12_REPORT.read_text(encoding="utf-8") if P.S12_REPORT.exists() else ""
    parts = {}
    for chunk in old.split("\n<!-- section: ")[1:]:
        key, body = chunk.split(" -->\n", 1)
        parts[key] = body.rstrip("\n")
    parts[name] = text.rstrip("\n")
    head = ("# Stage 12 report: the pipeline on new recordings (Phase 4)\n\nGenerated by `test_new_recording.py`. "
            "Criteria: `preregistration.md`.\n")
    P.S12_REPORT.write_text(head + "".join(f"\n<!-- section: {k} -->\n{parts[k]}\n" for k in sorted(parts)),
                            encoding="utf-8")


