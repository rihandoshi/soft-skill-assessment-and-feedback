def test_segment(attempt: int = 2) -> None:
    import mit_segment_answers as M
    import segment_interview as SI
    ref = pd.read_csv(P.S7_TABLES / "mit_answers.csv", dtype={"id": str})
    turns_all = M.load_turns()
    cache = P.CACHE_S12 / ("segments" if attempt == 1 else f"segments_attempt{attempt}")
    cache.mkdir(parents=True, exist_ok=True)
    embed, rows, irows = None, [], []
    for iid in M.interview_ids():
        f = cache / f"{iid}.json"
        if f.exists():
            got = json.loads(f.read_text())
        else:
            embed = embed or SI.SpeakerEmbedder(AA.device())
            words = json.loads((P.CACHE_MIT / "asr" / f"{iid}_{M.ASR_MODEL}.json").read_text(encoding="utf-8"))
            ans, info = SI.segment(M.mono16(iid), words, embed)
            spk, _, _ = M.align(turns_all[iid], words) if iid in turns_all else (np.array([None] * len(words)), 0, 0)
            lab = [(s, w) for s, w in zip(spk, info["word_speaker"]) if s is not None]
            got = {"answers": ans.to_dict("records"), "questions_found": info["questions_found"],
                   "n_turns": info["n_turns"], "words_labelled": len(lab),
                   "speaker_agreement": float(np.mean([s == w for s, w in lab])) if lab else None}
            f.write_text(json.dumps(got))
        irows.append({"interview": iid, "questions_found": got["questions_found"], "n_turns": got["n_turns"],
                      "speaker_agreement_with_turkers": got["speaker_agreement"]})
        for r in got["answers"]:
            rows.append({"interview": iid, **r})
        print(f"  {iid}: {got['questions_found']} speaker agreement {got['speaker_agreement']}", flush=True)
    report_gpu_peak()
    seg = pd.DataFrame(rows)
    num = lambda iid: int("".join(ch for ch in iid if ch.isdigit()))  # noqa: E731
    if attempt >= 2:   # addendum: criteria on even-numbered students; odd ones were used for development
        dev = ref[ref["interview"].map(num) % 2 == 1].merge(seg, on=["interview", "question"], how="left",
                                                             suffixes=("_stage7", "_new"))
        dev_found = dev["clip_start_s_new"].notna()
        dev_both = (((dev["clip_start_s_new"] - dev["clip_start_s_stage7"]).abs() <= SEG_TOL_S)
                    & ((dev["clip_end_s_new"] - dev["clip_end_s_stage7"]).abs() <= SEG_TOL_S))
        dev_line = (f"Development students (odd numbers, not a test): {dev_found.mean():.1%} found, "
                    f"{dev_both[dev_found].mean():.1%} within {SEG_TOL_S:g} s.\n\n")
        ref = ref[ref["interview"].map(num) % 2 == 0]
        seg = seg[seg["interview"].map(num) % 2 == 0]
        irows = [r for r in irows if num(r["interview"]) % 2 == 0]
    m = ref.merge(seg, on=["interview", "question"], how="left", suffixes=("_stage7", "_new"))
    m["start_diff_s"] = m["clip_start_s_new"] - m["clip_start_s_stage7"]
    m["end_diff_s"] = m["clip_end_s_new"] - m["clip_end_s_stage7"]
    found = m["clip_start_s_new"].notna()
    both = (m["start_diff_s"].abs() <= SEG_TOL_S) & (m["end_diff_s"].abs() <= SEG_TOL_S)
    absd = pd.concat([m.loc[found, "start_diff_s"].abs(), m.loc[found, "end_diff_s"].abs()])
    P.S12_TABLES.mkdir(parents=True, exist_ok=True)
    sfx = "" if attempt == 1 else f"_attempt{attempt}"
    m[["id", "interview", "question", "clip_start_s_stage7", "clip_end_s_stage7", "clip_start_s_new", "clip_end_s_new",
       "start_diff_s", "end_diff_s"]].to_csv(P.S12_TABLES / f"segment_answers{sfx}.csv", index=False)
    it = pd.DataFrame(irows)
    it.to_csv(P.S12_TABLES / f"segment_interviews{sfx}.csv", index=False)
    extra = seg.merge(ref[["interview", "question"]], how="left", indicator=True)
    n_extra = int((extra["_merge"] == "left_only").sum())
    share_found, share_both, med = float(found.mean()), float(both[found].mean()), float(absd.median())
    c1, c2, c3 = share_found >= 0.9, share_both >= 0.85, med <= 1.0
    verdict = "PASS" if c1 and c2 and c3 else "FAIL"
    worst = m[found & ~both].assign(worst=lambda d: d[["start_diff_s", "end_diff_s"]].abs().max(axis=1)) \
        .sort_values("worst", ascending=False).head(10)
    sa = it["speaker_agreement_with_turkers"].astype(float)
    title = ("## Test 2: MIT interviews segmented without the transcripts" if attempt == 1 else
             f"## Test 2, attempt {attempt}: held-out even-numbered students")
    text = (f"{title} ({verdict})\n\n"
            + (dev_line if attempt >= 2 else "") +
            f"{len(it)} interviews, {len(ref)} Stage 7 answers.\n\n"
            "| Criterion | Result | Bar | Met |\n|---|---|---|---|\n"
            f"| Stage 7 answers found | {found.sum()}/{len(m)} ({share_found:.1%}) | >= 90% | {c1} |\n"
            f"| Found answers with both boundaries within {SEG_TOL_S:g} s | {both[found].sum()}/{found.sum()} "
            f"({share_both:.1%}) | >= 85% | {c2} |\n"
            f"| Median absolute boundary difference | {med:.2f} s | <= 1 s | {c3} |\n\n"
            f"Answers found that Stage 7 does not have: {n_extra}.\n\n"
            f"Speaker split vs the Turker speaker labels (share of aligned words, per interview): median {sa.median():.3f}, "
            f"10th percentile {sa.quantile(0.1):.3f}, minimum {sa.min():.3f} ({it.loc[sa.idxmin(), 'interview']}).\n\n"
            f"Boundary differences (s), found answers:\n\n"
            f"{md(m.loc[found, ['start_diff_s', 'end_diff_s']].describe(), index=True)}\n\n"
            f"Largest misses:\n\n{md(worst[['id', 'clip_start_s_stage7', 'clip_start_s_new', 'clip_end_s_stage7', 'clip_end_s_new']])}\n")
    write_section("2_segment" if attempt == 1 else f"3_segment_attempt{attempt}", text)
    print(text)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--test", choices=["answers", "segment"], required=True)
    ap.add_argument("--max-gpu-frac", type=float, default=0.8)
    ap.add_argument("--reuse", action="store_true", help="answers: rebuild the report from the saved runs")
    ap.add_argument("--attempt", type=int, default=2, help="segment: 1 = first method (all students), 2 = held-out")
    args = ap.parse_args()
    cap_gpu_memory(args.max_gpu_frac)
    test_answers(args.reuse) if args.test == "answers" else test_segment(args.attempt)


if __name__ == "__main__":
    main()
