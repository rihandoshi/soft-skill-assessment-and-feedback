"""Phase 4, step 4: the two pre-registered tests (stage12_new_recordings/preregistration.md).

  --test answers   30 RecruitView validation answers through analyze_answer.py from the audio alone, compared with
                   their rows in answer_levels.csv. Run A: speaker context (pitch range, typical pitch) from the
                   dataset tables (the test). Run B: each clip alone (reported).
  --test segment   every MIT interview segmented by segment_interview.py (audio + Whisper words, no Turker
                   transcript), compared with the Stage 7 answer boundaries. Uses the cached Stage 7 Whisper words
                   (same model and settings as segment_interview.transcribe), so only the speaker split and the
                   answer finding are tested.

Output  stage12_new_recordings/tables/{answers_run_a,answers_run_b,answers_compare,segment_answers,
        segment_interviews}.csv and the sections of stage12_new_recordings/report.md
Run:    python scripts/explainability/test_new_recording.py --test answers     (about 10 min GPU)
        python scripts/explainability/test_new_recording.py --test segment     (about 10 min GPU)
"""
from __future__ import annotations

import argparse
